/**
 * FIT profile subset: message numbers, per-message field names, enum tables and
 * the official scale/offset/unit metadata for every field this plugin surfaces.
 *
 * The metadata is the part a naive dump misses: FIT stores most quantities as
 * scaled integers (distance in cm, speed in mm/s, altitude as (m + 500) * 5,
 * GPS coordinates in semicircles), so raw values are meaningless without it.
 */

